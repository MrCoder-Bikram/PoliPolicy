export interface ReceiptRow {
  label: string;
  value: string;
}

export function downloadDocument(options: {
  filename: string;
  title: string;
  subtitle: string;
  referenceId: string;
  rows: ReceiptRow[];
  tableSection?: {
    heading: string;
    columns: string[];
    rows: string[][];
  };
  footerNote?: string;
}) {
  const escapedRows = options.rows
    .map(
      (r) =>
        `<tr><th style="text-align:left;padding:10px 12px;border-bottom:1px solid #e2e8e5;color:#475569;font-weight:500;width:38%;">${escapeHtml(
          r.label
        )}</th><td style="padding:10px 12px;border-bottom:1px solid #e2e8e5;color:#0f2922;font-weight:600;">${escapeHtml(
          r.value
        )}</td></tr>`
    )
    .join('');

  const itemizedTableHtml = options.tableSection
    ? `<div style="margin-top:28px;">
        <h2 style="font-size:16px;margin:0 0 12px 0;color:#0f2922;">${escapeHtml(
          options.tableSection.heading
        )}</h2>
        <table style="margin-top:0;border:1px solid #e2e8e5;">
          <thead>
            <tr style="background:#f8fafc;">
              ${options.tableSection.columns
                .map(
                  (col) =>
                    `<th style="text-align:left;padding:10px 12px;border-bottom:1px solid #e2e8e5;color:#475569;font-size:12px;font-weight:600;">${escapeHtml(
                      col
                    )}</th>`
                )
                .join('')}
            </tr>
          </thead>
          <tbody>
            ${options.tableSection.rows
              .map(
                (row) =>
                  `<tr>${row
                    .map(
                      (cell) =>
                        `<td style="padding:9px 12px;border-bottom:1px solid #e2e8e5;color:#0f2922;font-size:13px;">${escapeHtml(
                          cell
                        )}</td>`
                    )
                    .join('')}</tr>`
              )
              .join('')}
          </tbody>
        </table>
      </div>`
    : '';

  const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>${escapeHtml(options.title)} — PoliPolicy</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif; background: #f7f9f8; color: #111c18; margin: 0; padding: 32px; }
    .card { max-width: 860px; margin: 0 auto; background: #ffffff; border: 1px solid #e2e8e5; border-radius: 14px; padding: 32px; }
    .header { display: flex; justify-content: space-between; align-items: flex-start; border-bottom: 2px solid #0f2922; padding-bottom: 16px; margin-bottom: 24px; }
    .brand { font-size: 20px; font-weight: 700; color: #0f2922; }
    .ref { font-family: monospace; font-size: 13px; color: #0d7a5f; }
    h1 { font-size: 22px; margin: 0 0 6px 0; color: #0f2922; }
    p.sub { margin: 0; font-size: 14px; color: #475569; }
    table { width: 100%; border-collapse: collapse; margin-top: 20px; font-size: 14px; }
    .footer { margin-top: 28px; padding-top: 16px; border-top: 1px solid #e2e8e5; font-size: 12px; color: #64748b; }
  </style>
</head>
<body>
  <div class="card">
    <div class="header">
      <div>
        <div class="brand">PoliPolicy</div>
        <div style="font-size:12px;color:#64748b;margin-top:4px;">Health Insurance Management System</div>
      </div>
      <div class="ref">${escapeHtml(options.referenceId)}</div>
    </div>
    <h1>${escapeHtml(options.title)}</h1>
    <p class="sub">${escapeHtml(options.subtitle)}</p>
    <table>
      ${escapedRows}
    </table>
    ${itemizedTableHtml}
    <div class="footer">
      ${escapeHtml(
        options.footerNote ||
          'Generated by PoliPolicy. Illustrative receipt, billing statement & policy summary document.'
      )}
    </div>
  </div>
</body>
</html>`;

  const blob = new Blob([html], { type: 'text/html;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = options.filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

function escapeHtml(text: string): string {
  return text
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}
